def _required_env(name):
    value = os.getenv(name)
    if value is None or value == '':
        raise ImproperlyConfigured(f'The {name} environment variable must be set.')
    return value


def _boolean_env(name):
    value = _required_env(name).strip().lower()
    if value in {'true', '1', 'yes', 'on'}:
        return True
    if value in {'false', '0', 'no', 'off'}:
        return False
    raise ImproperlyConfigured(f'The {name} environment variable must be a boolean.')


def _optional_boolean_env(name, default):
    value = os.getenv(name)
    if value is None:
        return default
    value = value.strip().lower()
    if value in {'true', '1', 'yes', 'on'}:
        return True
    if value in {'false', '0', 'no', 'off'}:
        return False
    raise ImproperlyConfigured(f'The {name} environment variable must be a boolean.')


def _nonnegative_integer_env(name, default):
    value = os.getenv(name, str(default))
    try:
        parsed = int(value)
    except ValueError as exc:
        raise ImproperlyConfigured(
            f'The {name} environment variable must be a non-negative integer.'
        ) from exc
    if parsed < 0:
        raise ImproperlyConfigured(
            f'The {name} environment variable must be a non-negative integer.'
        )
    return parsed


